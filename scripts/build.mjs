#!/usr/bin/env node
// Builds the static site from brand.json + pages/*.json, and regenerates the marketplace file.
// Usage: node scripts/build.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { landing, hub, privacy } from "../templates/parts.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => JSON.parse(fs.readFileSync(path.join(root, p), "utf8"));
const write = (p, s) => { fs.mkdirSync(path.dirname(path.join(root, p)), { recursive: true }); fs.writeFileSync(path.join(root, p), s); };

const brand = read("brand.json");
const pageFiles = fs.existsSync(path.join(root, "pages")) ? fs.readdirSync(path.join(root, "pages")).filter((f) => f.endsWith(".json")).sort() : [];
// Page files use paths relative to the skill's folder ("examples/kettle.html"). Pages are served at
// /<slug> without a trailing slash, so turn those into absolute paths ("/teachme/examples/kettle.html").
const absolutize = (p) => {
  const fix = (x) => (!x || /^(https?:|mailto:|\/|#)/.test(x) ? x : `/${p.slug}/${x}`);
  const q = structuredClone(p);
  q.name = q.name?.startsWith("/") ? q.name : `/${q.name || q.slug}`; // skills always show as /name
  if (q.demo) { q.demo.src = fix(q.demo.src); q.demo.liveUrl = fix(q.demo.liveUrl); }
  if (q.feature?.link) q.feature.link.href = fix(q.feature.link.href);
  for (const e of q.examples || []) { e.media = fix(e.media); e.href = fix(e.href); }
  for (const g of q.gallery?.items || []) { g.media = fix(g.media); g.href = fix(g.href); }
  if (q.gallery?.more) q.gallery.more.href = fix(q.gallery.more.href);
  q.cardMedia = fix(q.cardMedia);
  q.ogImage = q.ogImage ? fix(q.ogImage) : "";
  return q;
};
const pages = pageFiles.map((f) => read(`pages/${f}`)).filter((p) => !p.draft).map(absolutize);
const warnings = [];

for (const p of pages) {
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(p.slug)) throw new Error(`Bad slug "${p.slug}": use lowercase letters, numbers and hyphens.`);
  if (!fs.existsSync(path.join(root, "plugins", p.slug, "skills", p.slug, "SKILL.md")))
    warnings.push(`${p.slug}: plugins/${p.slug}/skills/${p.slug}/SKILL.md is missing.`);
  if (!fs.existsSync(path.join(root, "site", p.slug, "dl", `${p.slug}.zip`)))
    warnings.push(`${p.slug}: downloads not built yet. Run: node scripts/package.mjs ${p.slug}`);
  write(`site/${p.slug}/index.html`, landing(p, brand));
}
write("site/index.html", hub(pages, brand));
write("site/privacy.html", privacy(brand));

const site = brand.siteUrl.replace(/\/$/, "");
write("site/sitemap.xml", `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
  <url><loc>${site}/</loc></url>
${pages.map((p) => `  <url><loc>${site}/${p.slug}</loc></url>`).join("\n")}
</urlset>
`);
write("site/robots.txt", `User-agent: *\nAllow: /\nSitemap: ${site}/sitemap.xml\n`);

// What the signup functions need: brand details and each skill's name and link (for the welcome email).
const skills = Object.fromEntries(pages.map((p) => [p.slug, { name: p.name, tagline: p.tagline, url: `${site}/${p.slug}`, firstPrompt: p.prompts?.[0] || "" }]));
const brandPublic = { brandName: brand.brandName, byline: brand.byline, author: brand.author, siteUrl: site, email: brand.email, x: brand.x, substackUrl: brand.substackUrl };
write("api/_lib/data.mjs", `// Generated by scripts/build.mjs. Do not edit.\nexport const brand = ${JSON.stringify(brandPublic, null, 2)};\nexport const skills = ${JSON.stringify(skills, null, 2)};\n`);

// Marketplace: every plugin folder with a manifest is listed.
const pluginsDir = path.join(root, "plugins");
const plugins = fs.existsSync(pluginsDir) ? fs.readdirSync(pluginsDir).filter((d) => fs.existsSync(path.join(pluginsDir, d, ".claude-plugin", "plugin.json"))).sort() : [];
const entries = plugins.map((d) => {
  const m = JSON.parse(fs.readFileSync(path.join(pluginsDir, d, ".claude-plugin", "plugin.json"), "utf8"));
  if (m.name !== d) throw new Error(`plugins/${d}: plugin.json name "${m.name}" must equal the folder name.`);
  return { name: m.name, source: `./plugins/${d}`, description: m.description, version: m.version, homepage: m.homepage };
});
write(".claude-plugin/marketplace.json", JSON.stringify({
  name: brand.marketplaceName,
  description: `Free skills by ${brand.author}. ${site}`,
  owner: { name: brand.author, url: brand.authorUrl },
  plugins: entries,
}, null, 2) + "\n");

// Placeholders still waiting on the user.
const scan = JSON.stringify(brand) + pages.map((p) => JSON.stringify(p)).join("");
for (const m of new Set(scan.match(/TODO_[A-Z_]+/g) || [])) warnings.push(`placeholder still set: ${m}`);

console.log(`Built ${pages.length} skill page(s): ${pages.map((p) => p.slug).join(", ") || "none"}; marketplace lists ${entries.length} plugin(s).`);
for (const w of warnings) console.log(`  ! ${w}`);
